def field_hint(path: str, kind: str) -> str:
    """Resolve shared model fields and module switches without changing YAML."""

    normalized = re.sub(r"^models\.\d+\.", "model.", path)
    normalized = re.sub(r"^(ultralytics_model|custom_adapter)\.(name|weights|task)$", r"model.\2", normalized)
    if normalized in FIELD_HINTS:
        return FIELD_HINTS[normalized]
    if path.startswith("modules."):
        return "勾选启用此模块，取消勾选关闭；具体功能见当前工具说明。"
    return {
        "bool": "勾选启用，取消勾选关闭。",
        "number": "填写数字，保持原字段的数值类型。",
        "list": "多个值用逗号分隔，也可填写 YAML 列表；留空表示空列表。",
    }.get(kind, "填写文本或路径；自定义字段含义见对应工具说明。")
