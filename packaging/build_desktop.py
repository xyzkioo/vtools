"""Build the vtools desktop bundle with PyInstaller."""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DIST = ROOT / "vtools_ui" / "webapp" / "frontend" / "dist" / "index.html"
SOURCE_DIRS = (
    "config", "model_diagnostics", "model_visualization", "speed_test",
    "model_compression", "transform_tools", "others", "env_test", "vtools_runtime",
)
SOURCE_SUFFIXES = {".py", ".yaml", ".yml", ".json", ".cfg", ".txt", ".toml", ".typed"}
EXCLUDED_DIRS = {
    ".git", ".idea", ".vtools_ui", "__pycache__", ".pytest_cache",
    ".mypy_cache", ".ruff_cache", "node_modules", "runs", "runs-profile",
    "outputs", "tests", "weights", "build", "dist",
}


def source_datas() -> list[tuple[Path, str]]:
    """Return tracked tool sources and frontend files for the one-folder bundle."""

    tracked = subprocess.run(
        ["git", "-C", str(ROOT), "ls-files", "-z", "--", *SOURCE_DIRS],
        check=True,
        capture_output=True,
    ).stdout.decode("utf-8").split("\0")
    tracked_files = {ROOT / relative for relative in tracked if relative}
    datas: list[tuple[Path, str]] = [(ROOT / "run_tools.py", "tool-sources")]
    for directory in SOURCE_DIRS:
        for path in (ROOT / directory).rglob("*"):
            relative = path.relative_to(ROOT)
            if (
                path not in tracked_files
                or not path.is_file()
                or any(part in EXCLUDED_DIRS for part in relative.parts[1:])
                or path.suffix.lower() not in SOURCE_SUFFIXES
            ):
                continue
            datas.append((path, "tool-sources/" + relative.parent.as_posix()))
    frontend = ROOT / "vtools_ui" / "webapp" / "frontend" / "dist"
    for path in frontend.rglob("*"):
        if path.is_file():
            datas.append((path, path.relative_to(ROOT).parent.as_posix()))
    return datas


def main() -> int:
    parser = argparse.ArgumentParser(description="构建 React + Qt WebEngine 桌面目录包")
    parser.add_argument("--clean", action="store_true")
    args = parser.parse_args()
    if not DIST.is_file():
        raise SystemExit("请先构建 vtools_ui/webapp/frontend")
    if os.name == "nt" and (Path(sys.prefix) / "conda-meta").is_dir():
        raise SystemExit("Windows 请使用标准 CPython venv 和 packaging/requirements-windows-build.txt 构建")
    import PyInstaller
    from PySide6 import QtWebEngineWidgets, QtWebChannel
    import cv2
    import PIL.Image

    build = ROOT / "build"
    build.mkdir(exist_ok=True)
    datas = [(str(source), destination) for source, destination in source_datas()]
    icon = None
    if os.name == "nt":
        from vtools_icon import ensure_icon
        icon = str(ensure_icon())
        datas.append((icon, "."))
    excludes = ["pytest", "_pytest", "tests", "torch", "torchvision", "ultralytics",
                "matplotlib", "onnxruntime", "tensorrt", "cupy", "webview", "pythonnet", "clr", "clr_loader", "qtpy"]
    spec = build / "vtools.spec"
    text = f"""# Generated by packaging/build_desktop.py; do not edit.
a = Analysis([{str(ROOT / 'vtools_ui/__main__.py')!r}], pathex=[{str(ROOT)!r}],
    binaries=[], datas={datas!r},
    hiddenimports=['vtools_runtime', 'vtools_runtime.ultralytics', 'cv2', 'PIL.Image', 'PIL.ImageDraw', 'PIL.ImageOps'],
    hookspath=[], runtime_hooks=[], excludes={excludes!r}, noarchive=False)
pyz = PYZ(a.pure)
exe = EXE(pyz, a.scripts, [], exclude_binaries=True, name='vtools',
          console={os.name != 'nt'!r}, debug=False, strip=False, upx=False, icon={icon!r})
"""
    executables = "exe"
    if os.name == "nt":
        text += f"""worker = EXE(pyz, a.scripts, [], exclude_binaries=True, name='vtools-worker',
             console=True, debug=False, strip=False, upx=False, icon={icon!r})
"""
        executables += ", worker"
    text += f"coll = COLLECT({executables}, a.binaries, a.datas, strip=False, upx=False, name='vtools')\n"
    spec.write_text(text, encoding="utf-8")
    command = [sys.executable, "-m", "PyInstaller", "--noconfirm", "--distpath", str(ROOT / "dist"),
               "--workpath", str(build / "pyinstaller-qt")]
    if args.clean:
        command.append("--clean")
    result = subprocess.call([*command, str(spec)], cwd=ROOT)
    if result == 0 and os.name != "nt":
        # Preserve the existing Linux conda OpenSSL ABI repair.
        internal = ROOT / "dist/vtools/_internal"
        for name in ("libcrypto.so.3", "libssl.so.3"):
            source, target = Path(sys.prefix) / "lib" / name, internal / name
            if source.is_file() and target.is_file():
                shutil.copy2(source, target)
    return result


if __name__ == "__main__":
    raise SystemExit(main())
